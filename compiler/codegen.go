package main

import (
	"fmt"
	"strings"
)

// Calling convention (see spec/Zlang.md):
//   - the caller pushes the arguments left to right, calls, then pops them
//   - r0 is the accumulator and holds the return value
//   - r1 is a scratch register, r6 is the frame pointer, r7 is the stack pointer
//   - parameter i of n lives at [r6 + 4 + 2*(n-1-i)], locals at [r6 - 2*k]

// builtinArgs lists the built-in functions and how many arguments they take.
var builtinArgs = map[string]int{
	"print": 1, "putc": 1, "puts": 1, "peek": 1, "peekb": 1,
	"poke": 2, "pokeb": 2, "getc": 0, "sleep": 1, "halt": 0,
}

type Gen struct {
	out      strings.Builder
	funcs    map[string]*Func
	consts   map[string]int
	labelN   int
	strs     []string
	scopes   []map[string]int
	nlocals  int
	retLabel string
}

func isBuiltin(name string) bool {
	_, ok := builtinArgs[name]
	return ok
}

func (g *Gen) emit(format string, args ...interface{}) {
	fmt.Fprintf(&g.out, "    "+format+"\n", args...)
}

func (g *Gen) label(name string) { fmt.Fprintf(&g.out, "%s:\n", name) }

func (g *Gen) raw(line string) { g.out.WriteString(line + "\n") }

func (g *Gen) newLabel() string {
	g.labelN++
	return fmt.Sprintf("L%d", g.labelN)
}

func (g *Gen) lookup(name string) (int, bool) {
	for i := len(g.scopes) - 1; i >= 0; i-- {
		if off, ok := g.scopes[i][name]; ok {
			return off, true
		}
	}
	return 0, false
}

func (g *Gen) addString(s string) int {
	for i, old := range g.strs {
		if old == s {
			return i
		}
	}
	g.strs = append(g.strs, s)
	return len(g.strs) - 1
}

// escapeAsm writes a string so that zasm reads back the same bytes.
func escapeAsm(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case '\n':
			b.WriteString(`\n`)
		case '\t':
			b.WriteString(`\t`)
		case '\r':
			b.WriteString(`\r`)
		case 0:
			b.WriteString(`\0`)
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		default:
			b.WriteByte(c)
		}
	}
	return b.String()
}

// Generate turns a parsed program into ZX-16 assembly text.
func Generate(consts []*Const, funcs []*Func) (asm string, err error) {
	defer recoverError(&err)

	g := &Gen{funcs: map[string]*Func{}, consts: map[string]int{}}
	for _, c := range consts {
		if _, dup := g.consts[c.Name]; dup {
			fail(c.Line, "constant '%s' is defined twice", c.Name)
		}
		g.consts[c.Name] = c.Val
	}
	for _, f := range funcs {
		if isBuiltin(f.Name) {
			fail(f.Line, "'%s' is a built-in function and cannot be redefined", f.Name)
		}
		if _, dup := g.funcs[f.Name]; dup {
			fail(f.Line, "function '%s' is defined twice", f.Name)
		}
		g.funcs[f.Name] = f
	}
	m, ok := g.funcs["main"]
	if !ok {
		fail(1, "no 'main' function")
	}
	if len(m.Params) != 0 {
		fail(m.Line, "'main' must not take parameters")
	}

	g.raw("; generated by zlangc - do not edit")
	g.emit("call f_main")
	g.emit("halt")
	for _, f := range funcs {
		g.genFunc(f)
	}
	if len(g.strs) > 0 {
		g.raw("")
	}
	for i, s := range g.strs {
		g.label(fmt.Sprintf("str%d", i))
		g.emit(".string \"%s\"", escapeAsm(s))
	}
	return g.out.String(), nil
}

func countLocals(stmts []Stmt) int {
	n := 0
	for _, s := range stmts {
		switch st := s.(type) {
		case *VarStmt:
			n++
		case *IfStmt:
			n += countLocals(st.Then) + countLocals(st.Else)
		case *WhileStmt:
			n += countLocals(st.Body)
		}
	}
	return n
}

func (g *Gen) genFunc(f *Func) {
	g.retLabel = fmt.Sprintf("f_%s_ret", f.Name)
	g.scopes = []map[string]int{{}}
	g.nlocals = 0

	n := len(f.Params)
	for i, name := range f.Params {
		if _, dup := g.scopes[0][name]; dup {
			fail(f.Line, "duplicate parameter '%s' in function '%s'", name, f.Name)
		}
		g.scopes[0][name] = 4 + 2*(n-1-i)
	}

	total := countLocals(f.Body)
	g.raw("")
	g.label("f_" + f.Name)
	g.emit("push r6")
	g.emit("mov r6, r7")
	if total > 0 {
		g.emit("addi r7, %d", -2*total)
	}
	g.genStmts(f.Body)
	g.emit("ldi r0, 0") // falling off the end returns 0
	g.label(g.retLabel)
	g.emit("mov r7, r6")
	g.emit("pop r6")
	g.emit("ret")
}

func (g *Gen) genStmts(stmts []Stmt) {
	for _, s := range stmts {
		g.genStmt(s)
	}
}

func (g *Gen) genScoped(stmts []Stmt) {
	g.scopes = append(g.scopes, map[string]int{})
	g.genStmts(stmts)
	g.scopes = g.scopes[:len(g.scopes)-1]
}

func (g *Gen) genStmt(s Stmt) {
	switch st := s.(type) {
	case *VarStmt:
		top := g.scopes[len(g.scopes)-1]
		if _, dup := top[st.Name]; dup {
			fail(st.Line, "'%s' is already declared in this scope", st.Name)
		}
		g.genExpr(st.Init) // evaluated before the name exists
		g.nlocals++
		off := -2 * g.nlocals
		top[st.Name] = off
		g.emit("st [r6%+d], r0", off)

	case *AssignStmt:
		off, ok := g.lookup(st.Name)
		if !ok {
			if _, isConst := g.consts[st.Name]; isConst {
				fail(st.Line, "cannot assign to constant '%s'", st.Name)
			}
			fail(st.Line, "undefined variable '%s'", st.Name)
		}
		g.genExpr(st.Val)
		g.emit("st [r6%+d], r0", off)

	case *IfStmt:
		elseL, endL := g.newLabel(), g.newLabel()
		g.genExpr(st.Cond)
		g.emit("cmpi r0, 0")
		g.emit("jz %s", elseL)
		g.genScoped(st.Then)
		if len(st.Else) > 0 {
			g.emit("jmp %s", endL)
			g.label(elseL)
			g.genScoped(st.Else)
			g.label(endL)
		} else {
			g.label(elseL)
		}

	case *WhileStmt:
		topL, endL := g.newLabel(), g.newLabel()
		g.label(topL)
		g.genExpr(st.Cond)
		g.emit("cmpi r0, 0")
		g.emit("jz %s", endL)
		g.genScoped(st.Body)
		g.emit("jmp %s", topL)
		g.label(endL)

	case *ReturnStmt:
		g.genExpr(st.Val)
		g.emit("jmp %s", g.retLabel)

	case *ExprStmt:
		g.genExpr(st.X)

	default:
		panic("zlangc: unknown statement type")
	}
}

// genExpr emits code that leaves the value of e in r0.
func (g *Gen) genExpr(e Expr) {
	switch x := e.(type) {
	case *NumExpr:
		g.emit("ldi r0, %d", x.Val)

	case *StrExpr:
		g.emit("ldi r0, str%d", g.addString(x.Val)) // the address of the string

	case *VarExpr:
		if off, ok := g.lookup(x.Name); ok {
			g.emit("ld r0, [r6%+d]", off)
		} else if val, isConst := g.consts[x.Name]; isConst {
			g.emit("ldi r0, %d", val)
		} else {
			fail(x.Line, "undefined variable '%s'", x.Name)
		}

	case *UnaryExpr:
		g.genExpr(x.X)
		if x.Op == "-" {
			g.emit("ldi r1, 0")
			g.emit("sub r1, r0")
			g.emit("mov r0, r1")
		} else { // "!"
			yes, end := g.newLabel(), g.newLabel()
			g.emit("cmpi r0, 0")
			g.emit("jz %s", yes)
			g.emit("ldi r0, 0")
			g.emit("jmp %s", end)
			g.label(yes)
			g.emit("ldi r0, 1")
			g.label(end)
		}

	case *BinaryExpr:
		g.genBinary(x)

	case *CallExpr:
		g.genCall(x)

	default:
		panic("zlangc: unknown expression type")
	}
}

func (g *Gen) genBinary(x *BinaryExpr) {
	// short-circuit operators
	if x.Op == "&&" || x.Op == "||" {
		short, end := g.newLabel(), g.newLabel()
		jump, shortVal, otherVal := "jz", 0, 1
		if x.Op == "||" {
			jump, shortVal, otherVal = "jnz", 1, 0
		}
		g.genExpr(x.L)
		g.emit("cmpi r0, 0")
		g.emit("%s %s", jump, short)
		g.genExpr(x.R)
		g.emit("cmpi r0, 0")
		g.emit("%s %s", jump, short)
		g.emit("ldi r0, %d", otherVal)
		g.emit("jmp %s", end)
		g.label(short)
		g.emit("ldi r0, %d", shortVal)
		g.label(end)
		return
	}

	// left -> stack, right -> r1, left back into r0
	g.genExpr(x.L)
	g.emit("push r0")
	g.genExpr(x.R)
	g.emit("mov r1, r0")
	g.emit("pop r0")

	switch x.Op {
	case "+":
		g.emit("add r0, r1")
	case "-":
		g.emit("sub r0, r1")
	case "*":
		g.emit("mul r0, r1")
	case "/":
		g.emit("div r0, r1")
	case "%":
		g.emit("mod r0, r1")
	case "&":
		g.emit("and r0, r1")
	case "|":
		g.emit("or r0, r1")
	case "^":
		g.emit("xor r0, r1")
	case "<<":
		g.emit("shl r0, r1")
	case ">>":
		g.emit("shr r0, r1")
	case "==":
		g.compare("cmp r0, r1", "jz")
	case "!=":
		g.compare("cmp r0, r1", "jnz")
	case "<":
		g.compare("cmp r0, r1", "jlt")
	case ">=":
		g.compare("cmp r0, r1", "jge")
	case ">":
		g.compare("cmp r1, r0", "jlt")
	case "<=":
		g.compare("cmp r1, r0", "jge")
	default:
		panic("zlangc: unknown operator " + x.Op)
	}
}

// compare emits a comparison that leaves 1 or 0 in r0.
func (g *Gen) compare(cmp, jump string) {
	yes, end := g.newLabel(), g.newLabel()
	g.emit("%s", cmp)
	g.emit("%s %s", jump, yes)
	g.emit("ldi r0, 0")
	g.emit("jmp %s", end)
	g.label(yes)
	g.emit("ldi r0, 1")
	g.label(end)
}

func (g *Gen) genCall(c *CallExpr) {
	if want, ok := builtinArgs[c.Name]; ok {
		if len(c.Args) != want {
			fail(c.Line, "%s() takes %d argument(s), got %d", c.Name, want, len(c.Args))
		}
		g.genBuiltin(c)
		return
	}

	f, ok := g.funcs[c.Name]
	if !ok {
		fail(c.Line, "undefined function '%s'", c.Name)
	}
	if len(c.Args) != len(f.Params) {
		fail(c.Line, "function '%s' takes %d argument(s), got %d", c.Name, len(f.Params), len(c.Args))
	}
	for _, a := range c.Args {
		g.genExpr(a)
		g.emit("push r0")
	}
	g.emit("call f_%s", c.Name)
	if len(c.Args) > 0 {
		g.emit("addi r7, %d", 2*len(c.Args))
	}
}

func (g *Gen) genBuiltin(c *CallExpr) {
	switch c.Name {
	case "print":
		g.genExpr(c.Args[0])
		g.emit("outn r0")
	case "putc":
		g.genExpr(c.Args[0])
		g.emit("out r0")
	case "puts": // prints the zero-terminated string whose address is the argument
		loop, end := g.newLabel(), g.newLabel()
		g.genExpr(c.Args[0])
		g.emit("mov r1, r0")
		g.label(loop)
		g.emit("ldb r0, [r1]")
		g.emit("cmpi r0, 0")
		g.emit("jz %s", end)
		g.emit("out r0")
		g.emit("addi r1, 1")
		g.emit("jmp %s", loop)
		g.label(end)
	case "peek", "peekb":
		g.genExpr(c.Args[0])
		g.emit("mov r1, r0")
		if c.Name == "peek" {
			g.emit("ld r0, [r1]")
		} else {
			g.emit("ldb r0, [r1]")
		}
	case "poke", "pokeb":
		g.genExpr(c.Args[0])
		g.emit("push r0")
		g.genExpr(c.Args[1])
		g.emit("pop r1")
		if c.Name == "poke" {
			g.emit("st [r1], r0")
		} else {
			g.emit("stb [r1], r0")
		}
	case "getc":
		g.emit("in r0")
	case "sleep":
		g.genExpr(c.Args[0])
		g.emit("sleep r0")
	case "halt":
		g.emit("halt")
	}
}
