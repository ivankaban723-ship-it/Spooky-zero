#!/usr/bin/env python3
"""Generates studio/examples.js: every example with its source and precompiled binary.

The Studio page loads this file, so the examples run even without the server.
Usage: python3 tools/build_studio.py [--check]
"""
import base64
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [os.path.join(ROOT, "assembler"), os.path.join(ROOT, "tools")]
import zasm      # noqa: E402
import zlangc    # noqa: E402

# (file, title) in the order shown in the Studio
EXAMPLES = [
    ("snake.zl", "Snake (game, Zlang)"),
    ("shell.zl", "ZOS shell (mini OS, Zlang)"),
    ("hello.zl", "Hello (Zlang)"),
    ("fib.zl", "Fibonacci (Zlang)"),
    ("primes.zl", "Primes (Zlang)"),
    ("ops.zl", "Operators (Zlang)"),
    ("hello.zasm", "Hello (assembly)"),
    ("fib.zasm", "Fibonacci (assembly)"),
    ("primes.zasm", "Primes (assembly)"),
]


def generate():
    items = []
    for filename, title in EXAMPLES:
        with open(os.path.join(ROOT, "examples", filename), encoding="utf-8") as f:
            source = f.read()
        if filename.endswith(".zl"):
            lang, asm = "zl", zlangc.compile_source(source)
        else:
            lang, asm = "zasm", source
        items.append({
            "id": filename,
            "title": title,
            "lang": lang,
            "source": source,
            "asm": asm if lang == "zl" else "",
            "bin": base64.b64encode(zasm.assemble(asm)).decode("ascii"),
        })
    return "// generated by tools/build_studio.py - do not edit\nwindow.EXAMPLES = " + json.dumps(items, indent=1, ensure_ascii=False) + ";\n"


def main_check():
    """True when studio/examples.js matches the current examples."""
    with open(os.path.join(ROOT, "studio", "examples.js"), encoding="utf-8") as f:
        return f.read() == generate()


def main():
    text = generate()
    path = os.path.join(ROOT, "studio", "examples.js")
    if "--check" in sys.argv:
        with open(path, encoding="utf-8") as f:
            return 0 if f.read() == text else 1
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {path} ({len(EXAMPLES)} examples)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
